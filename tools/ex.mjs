import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)(process.env.PW || 'playwright');
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1440, height: 820 } });
p.on('pageerror', e => console.log('PAGEERR', e.message));
const t0 = Date.now();
await p.goto('http://localhost:5173/');
await p.waitForFunction(() => window.__app, null, { timeout: 90000 });
console.log('caricamento ms', Date.now() - t0);
await p.click('#btn-explode');
await p.waitForFunction(() => window.__app.state.explode > 0.999, null, { timeout: 120000 });
await p.waitForTimeout(6000);
await p.screenshot({ path: 'shots/ex.png' });
const fps = await p.evaluate(() => new Promise(r => { let n = 0; const t = performance.now(); const f = () => { n++; if (performance.now() - t > 2000) r(n / 2); else { window.__app.invalidate(); requestAnimationFrame(f); } }; f(); }));
console.log('fps (software)', fps);
await b.close();
